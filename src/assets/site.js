const LANGUAGE_STORAGE_KEY = 'ww_language';

function getStoredLanguage() {
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return translations[stored] ? stored : null;
  } catch (error) {
    return null;
  }
}

function applyLanguage(lang) {
  const target = translations[lang] ? lang : 'en';
  document.documentElement.lang = target;
  document.documentElement.dir = target === 'ar' ? 'rtl' : 'ltr';
  document.body.classList.toggle('lang-ar', target === 'ar');

  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, target);
  } catch (error) {
    // Ignore storage failures and keep the current page state working.
  }

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    const value = translations[target][key];
    if (value) {
      if (el.dataset.i18nHtml === 'true') {
        el.innerHTML = value;
      } else {
        el.textContent = value;
      }
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    const value = translations[target][key];
    if (value) {
      el.placeholder = value;
    }
  });

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('is-active', btn.dataset.lang === target);
  });

  document.querySelectorAll('[data-site-setting]').forEach((el) => {
    const key = el.dataset.siteSetting;
    const value = siteSettings[key]?.[target];
    if (value) {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-site-setting-src]').forEach((el) => {
    const key = el.dataset.siteSettingSrc;
    const value = siteSettings[key]?.[target];
    if (value && el instanceof HTMLImageElement) {
      el.src = value;
      el.classList.remove('is-hidden');
    } else if (el instanceof HTMLImageElement) {
      el.classList.add('is-hidden');
    }
  });

  document.querySelectorAll('[data-site-setting-alt]').forEach((el) => {
    const key = el.dataset.siteSettingAlt;
    const value = siteSettings[key]?.[target];
    if (value && el instanceof HTMLImageElement) {
      el.alt = value;
    }
  });

  document.querySelectorAll('[data-social-label-en]').forEach((el) => {
    const value = target === 'ar' ? el.dataset.socialLabelAr : el.dataset.socialLabelEn;
    if (value) {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-blog-copy]').forEach((el) => {
    const value = target === 'ar' ? el.dataset.blogAr : el.dataset.blogEn;
    if (value) {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-blog-placeholder-en]').forEach((el) => {
    const value = target === 'ar' ? el.dataset.blogPlaceholderAr : el.dataset.blogPlaceholderEn;
    if (value && 'placeholder' in el) {
      el.placeholder = value;
    }
  });

  document.querySelectorAll('[data-blog-option-en]').forEach((el) => {
    const value = target === 'ar' ? el.dataset.blogOptionAr : el.dataset.blogOptionEn;
    if (value) {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-blog-html]').forEach((el) => {
    const value = target === 'ar' ? el.dataset.blogHtmlAr : el.dataset.blogHtmlEn;
    if (value) {
      el.innerHTML = value;
    }
  });

  document.querySelectorAll('[data-blog-alt-en]').forEach((el) => {
    const value = target === 'ar' ? el.dataset.blogAltAr : el.dataset.blogAltEn;
    if (value && el instanceof HTMLImageElement) {
      el.alt = value;
    }
  });

  document.querySelectorAll('[data-deep-dive-copy]').forEach((el) => {
    const value = target === 'ar' ? el.dataset.deepDiveAr : el.dataset.deepDiveEn;
    if (value) {
      el.textContent = value;
    }
  });
}

