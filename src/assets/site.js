(function () {
  const scroller = document.querySelector('.team-scroller');
  const row = document.querySelector('.team-row');
  const btnNext = document.querySelector('.team-nav-next');
  const btnPrev = document.querySelector('.team-nav-prev');
  if (!scroller || !row || !btnNext || !btnPrev) return;

  function scrollStep(direction = 1) {
    const width = scroller.offsetWidth;
    const maxScroll = row.scrollWidth - width;
    let target = scroller.scrollLeft + direction * width * 0.7;

    if (target < 0) {
      target = maxScroll;
    } else if (target > maxScroll + 40) {
      target = 0;
    }

    scroller.scrollTo({ left: target, behavior: 'smooth' });
  }

  btnNext.addEventListener('click', () => scrollStep(1));
  btnPrev.addEventListener('click', () => scrollStep(-1));

  let autoTimer = setInterval(() => scrollStep(1), 3000);

  function pauseAuto() {
    if (autoTimer) {
      clearInterval(autoTimer);
      autoTimer = null;
    }
  }

  function resumeAuto() {
    if (!autoTimer) {
      autoTimer = setInterval(() => scrollStep(1), 3000);
    }
  }

  scroller.addEventListener('mouseenter', pauseAuto);
  scroller.addEventListener('mouseleave', resumeAuto);
})();

