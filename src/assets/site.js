// Click-to-load YouTube facade (Vibe Test video). The heavy YouTube iframe is
// only created after the visitor clicks, so page load stays light. The anchor
// href is the admin-editable video URL; anything that is not a YouTube link
// keeps the block hidden, which is how admins turn the video off.
(function () {
  function parseYouTubeId(url) {
    if (!url) return null;
    const match = url.match(
      /(?:youtube(?:-nocookie)?\.com\/(?:watch\?[^#]*v=|embed\/|shorts\/|live\/)|youtu\.be\/)([\w-]{11})/
    );
    return match ? match[1] : null;
  }

  document.querySelectorAll('[data-youtube-facade]').forEach((facade) => {
    const wrap = facade.closest('.sara-video');
    const media = facade.querySelector('[data-video-media]');
    const videoId = parseYouTubeId(facade.getAttribute('href'));
    if (!wrap || !media || !videoId) return;

    const thumb = document.createElement('img');
    thumb.alt = '';
    thumb.loading = 'lazy';
    thumb.src = `https://i.ytimg.com/vi/${videoId}/maxresdefault.jpg`;
    // Videos without a maxres thumbnail return a tiny gray placeholder (HTTP 200),
    // so a load-size check is needed in addition to the error fallback.
    thumb.addEventListener('load', () => {
      if (thumb.naturalWidth < 200 && thumb.src.includes('maxresdefault')) {
        thumb.src = `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`;
      }
    });
    thumb.addEventListener('error', () => {
      if (thumb.src.includes('maxresdefault')) {
        thumb.src = `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`;
      }
    });
    media.appendChild(thumb);
    wrap.classList.add('is-ready');

    facade.addEventListener('click', (event) => {
      if (facade.classList.contains('is-playing')) return;
      event.preventDefault();

      const iframe = document.createElement('iframe');
      iframe.src = `https://www.youtube-nocookie.com/embed/${videoId}?autoplay=1&rel=0`;
      iframe.title = facade.querySelector('.sara-video-label')?.textContent || 'Video';
      iframe.allow = 'accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share';
      iframe.setAttribute('allowfullscreen', '');
      media.appendChild(iframe);

      facade.classList.add('is-playing');
      // Neutralize the link so keyboard focus stays on the player instead of
      // re-triggering navigation to youtube.com.
      facade.removeAttribute('href');
      facade.removeAttribute('target');
    });
  });
})();
